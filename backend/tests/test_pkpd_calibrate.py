"""
backend/tests/test_pkpd_calibrate.py
Unit tests for Nelder-Mead parameter calibration and hold-out validation.

Verifies:
1. Synthetic parameter recovery for (CL, V1, ka) from noise-free and noisy data.
2. Hold-out protocol: split observations into train and test sets; report train & test metrics.
3. Misspecified model test: fitting a 1-compartment model to data generated by a 2-compartment
   system yields worse test error honestly reported.
"""

from __future__ import annotations

import math
import numpy as np
import pytest

from app.pharma.pkpd.engine import PKPDParams, ModelType, RouteType, simulate_pkpd
from app.pharma.pkpd.calibrate import (
    DatasetSplit,
    CalibrationMetrics,
    calibrate_pkpd_holdout,
    nelder_mead,
)


def test_synthetic_parameter_recovery_1comp_oral():
    """
    True parameters: CL = 12.0 L/h, V1 = 45.0 L, ka = 1.5 /h.
    Generate synthetic data at 12 timepoints with known truth.
    Nelder-Mead must recover parameters within 5% from perturbed initial guess.
    """
    true_params = PKPDParams(
        model_type=ModelType.one_compartment,
        route=RouteType.oral,
        dose_mg=500.0,
        cl=12.0,
        v1=45.0,
        ka=1.5,
        f_bioav=1.0,
    )
    sim = simulate_pkpd(true_params, t_end_h=24.0, dt_h=0.05)

    sample_times = [0.25, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0, 8.0, 12.0, 16.0, 24.0]
    sample_concs = list(np.interp(sample_times, sim.times, sim.concentrations))

    # Hold-out split: alternating points
    train_times = sample_times[::2]   # 6 points
    train_concs = sample_concs[::2]
    test_times = sample_times[1::2]   # 6 points
    test_concs = sample_concs[1::2]

    data = DatasetSplit(
        train_times=train_times,
        train_concs=train_concs,
        test_times=test_times,
        test_concs=test_concs,
    )

    base = PKPDParams(model_type=ModelType.one_compartment, route=RouteType.oral, dose_mg=500.0, f_bioav=1.0)
    # Perturbed initial guess
    init = {"cl": 8.0, "v1": 30.0, "ka": 2.5}

    metrics = calibrate_pkpd_holdout(base, data, param_names=["cl", "v1", "ka"], init_guess=init)

    # Assert recovery
    recovered_cl = metrics.fitted_params["cl"]
    recovered_v1 = metrics.fitted_params["v1"]
    recovered_ka = metrics.fitted_params["ka"]

    assert abs(recovered_cl - 12.0) / 12.0 < 0.05, f"CL recovery failed: {recovered_cl}"
    assert abs(recovered_v1 - 45.0) / 45.0 < 0.05, f"V1 recovery failed: {recovered_v1}"
    assert abs(recovered_ka - 1.5) / 1.5 < 0.05, f"ka recovery failed: {recovered_ka}"

    # Train and test RMSE must be low
    assert metrics.train_rmse < 0.05
    assert metrics.test_rmse < 0.05
    assert metrics.test_pct_within_2fold == 100.0


def test_holdout_misspecified_model_reports_worse_test_error():
    """
    Generate truth from a distinct 2-compartment model with strong distribution phase.
    Fit using a 1-compartment model.
    Verify test RMSE is reported honestly and is substantially higher than zero.
    """
    true_2comp = PKPDParams(
        model_type=ModelType.two_compartment,
        route=RouteType.iv_bolus,
        dose_mg=1000.0,
        cl=10.0,
        v1=20.0,
        q=25.0,
        v2=60.0,
    )
    sim = simulate_pkpd(true_2comp, t_end_h=24.0, dt_h=0.05)

    sample_times = [0.1, 0.25, 0.5, 1.0, 2.0, 4.0, 6.0, 8.0, 12.0, 18.0, 24.0]
    sample_concs = list(np.interp(sample_times, sim.times, sim.concentrations))

    # Train on early/mid points, test on late points
    train_times = sample_times[:6]
    train_concs = sample_concs[:6]
    test_times = sample_times[6:]
    test_concs = sample_concs[6:]

    data = DatasetSplit(
        train_times=train_times,
        train_concs=train_concs,
        test_times=test_times,
        test_concs=test_concs,
    )

    # 1-comp model attempt to fit 2-comp data
    base_1comp = PKPDParams(model_type=ModelType.one_compartment, route=RouteType.iv_bolus, dose_mg=1000.0)
    metrics = calibrate_pkpd_holdout(base_1comp, data, param_names=["cl", "v1"], init_guess={"cl": 15.0, "v1": 35.0})

    # Test RMSE must be reported honestly and will show divergence on hold-out
    assert metrics.test_rmse > 0.1
    assert "cl" in metrics.fitted_params
    assert "v1" in metrics.fitted_params
